import { readFileSync, writeFileSync } from 'node:fs';
import { sql } from './data-utils';

/**
 * Chinese search names and ranking for locations.
 *
 * The location source has Chinese names for very few Chinese cities, and its
 * translations attach to homonyms in other provinces (e.g. "Suzhou" in Anhui is 宿州).
 * Curated names are therefore matched by province plus a normalized romanization,
 * and any curated Chinese name found on a different city is removed first.
 */
type Curated = Record<string, [string, ...string[]][]>;

/** SQL that lower-cases and strips punctuation/diacritics the source uses in Chinese place names. */
const normalized = (column: string) => {
  let expr = column;
  for (const [from, to] of [
    ["'", ''],
    ['’', ''],
    [' ', ''],
    ['-', ''],
    [',', ''],
    ['.', ''],
    ['ü', 'u'],
    ['Ü', 'U'],
    ['ê', 'e'],
    ['ō', 'o'],
  ])
    expr = `replace(${expr},${sql(from)},${sql(to)})`;
  return `lower(${expr})`;
};
const ascii = (value: string) => value.toLowerCase().replace(/[^a-z]/g, '');
const aliasForm = (value: string) =>
  value
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .trim();

export function locationFixSQL(root = '.') {
  const china = JSON.parse(readFileSync(`${root}/data/china-cities.zh-CN.json`, 'utf8')) as Curated;
  const world = JSON.parse(
    readFileSync(`${root}/data/location-names.zh-CN.json`, 'utf8'),
  ) as Record<string, Record<string, string>>;
  const chinaCities = `SELECT id FROM locations WHERE country_code='CN' AND kind='city'`;
  const names = [...new Set(Object.values(china).flatMap((list) => list.map(([zh]) => zh)))];
  const queries = [
    // Ranking: curated cities first, then countries, then everything else.
    `UPDATE locations SET popularity=1 WHERE kind='country' AND popularity<1;`,
    `UPDATE locations SET name_zh='' WHERE country_code='CN' AND kind='city' AND name_zh IN (${names.map(sql).join(',')});`,
    `DELETE FROM location_aliases WHERE alias IN (${names.map(sql).join(',')}) AND location_id IN (${chinaCities});`,
  ];
  for (const [region, list] of Object.entries(china))
    for (const [zh, ...romanized] of list) {
      const keys = [...new Set(romanized.map(ascii))];
      const where = `country_code='CN' AND kind='city' AND region=${sql(region)} AND ${normalized('name')} IN (${keys.map(sql).join(',')})`;
      queries.push(`UPDATE locations SET name_zh=${sql(zh)},popularity=3 WHERE ${where};`);
      for (const alias of new Set([zh, ...romanized.map(aliasForm)]))
        queries.push(
          `INSERT OR IGNORE INTO location_aliases(location_id,alias) SELECT id,${sql(alias)} FROM locations WHERE ${where};`,
        );
    }
  for (const [country, entries] of Object.entries(world))
    for (const [name, zh] of Object.entries(entries)) {
      const where = `country_code=${sql(country)} AND kind='city' AND ${normalized('name')}=${sql(ascii(name))}`;
      queries.push(`UPDATE locations SET name_zh=${sql(zh)},popularity=2 WHERE ${where};`);
      queries.push(
        `INSERT OR IGNORE INTO location_aliases(location_id,alias) SELECT id,${sql(zh)} FROM locations WHERE ${where};`,
      );
    }
  return queries;
}

/** Relink catalog spots whose city was matched in the wrong province, and their visits/wishes. */
export function scenicRelinkSQL(root = '.') {
  const spots = JSON.parse(readFileSync(`${root}/src/data/scenic-spots.json`, 'utf8')) as {
    id: string;
    city: string;
    region_en: string;
  }[];
  return spots.flatMap((s) => {
    const target = `(SELECT id FROM locations WHERE country_code='CN' AND kind='city' AND name=${sql(s.city)} AND region LIKE ${sql(s.region_en + '%')} ORDER BY popularity DESC,id LIMIT 1)`;
    const current = `(SELECT location_id FROM scenic_spots WHERE id=${sql(s.id)})`;
    return [
      `UPDATE scenic_spots SET location_id=${target} WHERE id=${sql(s.id)} AND ${target} IS NOT NULL;`,
      `UPDATE travel_entries SET location_id=${current} WHERE spot_id=${sql(s.id)};`,
      `UPDATE travel_wishlist SET location_id=${current} WHERE spot_id=${sql(s.id)};`,
    ];
  });
}

if (process.argv[1]?.endsWith('location-fixes.ts')) {
  const target = process.argv[2];
  if (!target) throw new Error('Usage: tsx scripts/location-fixes.ts <migration.sql>');
  writeFileSync(
    target,
    `-- Generated by scripts/location-fixes.ts from data/china-cities.zh-CN.json and data/location-names.zh-CN.json.\n-- Province-aware Chinese city names, search ranking and scenic spot links.\nALTER TABLE locations ADD COLUMN popularity INTEGER NOT NULL DEFAULT 0;\nCREATE INDEX IF NOT EXISTS location_region ON locations(country_code,kind,region);\n${[...locationFixSQL(), ...scenicRelinkSQL()].join('\n')}\n`,
  );
}
